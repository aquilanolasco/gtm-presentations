"use client";

/* The engage deck's slide library: every master slide a rep can put after the prospect's opening
   slides (Introduction deck, Sales deck, Short Pack, and any vertical variants of the first two).
   The catalogue (one id space, deck order = order in a generated deck) and the lifted markup
   (generated by scripts/gen-library.py) are not part of this export: ./sample-slides stands in for
   both with the same shape. The Short Pack's six are still rendered by the engage page itself.

   A body entry is a library sid ("intro-leadership"), or "<sid>~<savedId>": that master slide with
   the words / photos / hidden items a rep saved from another deck (a Saved slide, see the GTM app's
   /api/presentations/save-slide). The deck renders the same master markup under the longer id; the
   saved patch travels in the deck's edits.json, keyed by that id. */

import { scopeCss } from "./scope-css";
// sample library (original: library.json + intro/sales slide files and their vertical variants)
import { SAMPLE_LIB as LIB, SALES_SLIDES, SALES_CSS, INTRO_SLIDES, INTRO_CSS, INTRO_Runtime } from "./sample-slides";
import type { ReactNode } from "react";

export type LibSlide = { sid: string; id: string; label: string; title: string; dark?: boolean };
export type LibDeck = { id: string; title: string; blurb?: string; slides: LibSlide[] };
export type LibEntry = LibSlide & { deck: string; deckOrder: number; order: number };

export const LIBRARY: LibDeck[] = LIB.decks as LibDeck[];
export const LIB_INDEX: Record<string, LibEntry> = {};
LIBRARY.forEach((d, di) => d.slides.forEach((s, si) => { LIB_INDEX[s.sid] = { ...s, deck: d.id, deckOrder: di, order: si }; }));

/* the Short Pack, as every deck before the library shipped */
export const DEFAULT_BODY: string[] = (LIBRARY.find((d) => d.id === "shortpack")?.slides || []).map((s) => s.sid);

/* "<sid>~<savedId>" -> the master slide it is based on */
export const baseOf = (ref: string): string => ref.split("~")[0];
export const entryOf = (ref: string): LibEntry | undefined => LIB_INDEX[baseOf(ref)];
const REF = /^[a-z0-9-]+(~[a-z0-9]{4,16})?$/;

/* A spec's body as the deck shows it: known slides only, legacy bare ids are the Short Pack's, no
   duplicates, and always in library order (deck, then the master's own order, a saved variant right
   after its master), whatever order the rep ticked them in. Empty or missing = the Short Pack. */
export function normalizeBody(list: unknown): string[] {
  const raw = Array.isArray(list) ? list.filter((x): x is string => typeof x === "string") : [];
  const seen = new Set<string>();
  const out = raw.map((x) => x.replace(/^shortpack:/, "")).filter((x) => REF.test(x) && entryOf(x) && !seen.has(x) && seen.add(x));
  if (!out.length) return [...DEFAULT_BODY];
  const key = (x: string) => { const e = entryOf(x)!; return [e.deckOrder, e.order, x.includes("~") ? 1 : 0]; };
  return out.sort((a, b) => { const ka = key(a), kb = key(b); return (ka[0] - kb[0]) || (ka[1] - kb[1]) || (ka[2] - kb[2]) || a.localeCompare(b); });
}

/* rendered by <LibrarySlide> (the engage page renders the Short Pack's own six) */
export const isLibraryRendered = (ref: string): boolean => { const e = entryOf(ref); return !!e && e.deck !== "shortpack"; };

type Render = (sid: string) => ReactNode;
// one entry per master deck id; vertical variants ("intro-<x>", "sales-<x>") plug in the same way
const RENDER: Record<string, Record<string, Render>> = {
  intro: INTRO_SLIDES, sales: SALES_SLIDES,
};
const RAW_CSS: Record<string, string> = {
  intro: INTRO_CSS, sales: SALES_CSS,
};
const SCOPED: Record<string, string> = {};
const scoped = (deck: string): string => (SCOPED[deck] ??= scopeCss(RAW_CSS[deck] || "", `.lib-${deck}`));

/* the masters' own stylesheets, scoped to the slides lifted from them (only the decks on the page) */
export function LibraryStyles({ decks }: { decks: string[] }) {
  const ds = decks.filter((d) => RAW_CSS[d]);
  if (!ds.length) return null;
  return <style data-lib-styles={ds.join(" ")}>{ds.map(scoped).join("\n")}</style>;
}

/* the Introduction decks' mount-time work (scaling the embedded product screens), once per page */
export function LibraryRuntime({ decks }: { decks: string[] }) {
  return decks.some((d) => d.startsWith("intro")) ? <INTRO_Runtime /> : null;
}

/* one library slide, wrapped in its deck's scope (display: contents, so the deck still sees a plain
   run of .pp-slide sections). `sid` may carry a ~savedId suffix; the markup is the base slide's. */
export function LibrarySlide({ sid }: { sid: string }) {
  const e = entryOf(sid);
  if (!e) return null;
  const r = RENDER[e.deck]?.[e.id];
  if (!r) return null;
  return <div className={`lib-${e.deck}`} style={{ display: "contents" }}>{r(sid)}</div>;
}
